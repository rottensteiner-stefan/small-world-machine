import { AbstractGeometry } from "./AbstractGeometry.js";
import { LatheGeometry, type LatheRing } from "./LatheGeometry.js";

/**
 * Configuration options for tube geometry.
 */
export interface TubeOptions {
  /** The outer radius of the tube. Defaults to 1. */
  radius?: number;
  /** The inner radius of the tube (hole size). Defaults to 0.5. */
  innerRadius?: number;
  /** The total height of the tube. Defaults to 2. */
  height?: number;
  /** The number of radial segments. Defaults to 16. */
  radialSegments?: number;
  /** The number of height segments along the vertical axis. Defaults to 1. */
  heightSegments?: number;
}

/**
 * A hollow cylinder geometry (Tube).
 *
 * Cap vertices are kept separate from the mantle vertices so {@link computeNormals}
 * does not average normals across the 90-degree edge. The surface is generated by the
 * shared revolve core ({@link LatheGeometry}), whose cap emission always uses dedicated
 * vertices.
 */
export class Tube extends AbstractGeometry {
  /** The outer radius. */
  public radius: number;
  /** The inner radius. */
  public innerRadius: number;
  /** The height. */
  public height: number;
  /** The number of radial segments. */
  public radialSegments: number;
  /** The number of height segments. */
  public heightSegments: number;

  /**
   * Creates a new Tube geometry.
   * @param options The configuration options.
   */
  constructor(options: TubeOptions = {}) {
    super();
    const {
      radius = 1,
      innerRadius = 0.5,
      height = 2,
      radialSegments = 16,
      heightSegments = 1,
    } = options;
    this.radius = Math.max(0, radius);
    this.innerRadius = Math.max(0, Math.min(innerRadius, this.radius));
    this.height = Math.max(0, height);
    this.radialSegments = Math.max(3, Math.floor(radialSegments));
    this.heightSegments = Math.max(1, Math.floor(heightSegments));
    this.generateGeometryData();
  }

  /** @inheritdoc */
  protected override generateGeometryData(): void {
    const hh = this.height / 2.0;
    const rings: LatheRing[] = [];
    for (let y = 0; y <= this.heightSegments; y++) {
      const vCoord = y / this.heightSegments;
      rings.push({
        outer: this.radius,
        inner: this.innerRadius,
        y: vCoord * this.height - hh,
      });
    }

    const core = new LatheGeometry({
      rings,
      radialSegments: this.radialSegments,
      thetaStart: 0,
      thetaLength: 2 * Math.PI,
      capTop: true,
      capBottom: true,
      sideCaps: false,
      flipInnerU: false,
    });
    this.setBuffers({
      vertices: core.vertices,
      uvs: core.uvs,
      indices: core.indices,
      wireframeIndices: core.wireframeIndices,
      normals: core.normals,
    });
  }
}
