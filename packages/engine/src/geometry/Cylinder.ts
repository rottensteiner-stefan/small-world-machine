import { AbstractGeometry } from "./AbstractGeometry.js";
import { LatheGeometry, type LatheRing } from "./LatheGeometry.js";
import { MathUtils } from "../math/index.js";

/**
 * Configuration options for cylinder geometry.
 */
export interface CylinderOptions {
  /** The radius at the top. Defaults to 1. Set to 0 for a cone. */
  radiusTop?: number;
  /** The radius at the bottom. Defaults to 1. */
  radiusBottom?: number;
  /** The total height of the cylinder. Defaults to 2. */
  height?: number;
  /** The number of radial segments around the circumference. Defaults to 16. */
  radialSegments?: number;
  /** The number of height segments along the vertical axis. Defaults to 1. */
  heightSegments?: number;
  /** The start angle of the sector in radians. Defaults to 0. */
  thetaStart?: number;
  /** The central angle of the sector in radians. Defaults to 2 * PI (full cylinder). */
  thetaLength?: number;
  /** Whether the cylinder ends are open (no top and bottom caps). Defaults to false. */
  openEnded?: boolean;
  /** UV repeat factor for the side surface [uRepeat, vRepeat]. Defaults to [1, 1]. */
  sideUvRepeat?: [number, number];
}

/**
 * A generalized cylinder geometry.
 * Can represent standard cylinders, cones (top radius 0), and conical frustums.
 * Supports partial sectors (pie slices) via thetaStart and thetaLength.
 *
 * The surface is generated by the shared revolve core ({@link LatheGeometry}).
 */
export class Cylinder extends AbstractGeometry {
  /** The radius at the top. */
  public radiusTop: number;
  /** The radius at the bottom. */
  public radiusBottom: number;
  /** The total height. */
  public height: number;
  /** The number of radial segments. */
  public radialSegments: number;
  /** The number of height segments. */
  public heightSegments: number;
  /** The start angle in radians. */
  public thetaStart: number;
  /** The central angle in radians. */
  public thetaLength: number;
  /** Whether the cylinder ends are open (no caps). */
  public openEnded: boolean;
  /** UV repeat factor for the side surface [uRepeat, vRepeat]. */
  public sideUvRepeat: [number, number];

  /**
   * Creates a new Cylinder geometry.
   * @param options The configuration options.
   */
  constructor(options: CylinderOptions = {}) {
    super();
    const {
      radiusTop = 1,
      radiusBottom = 1,
      height = 2,
      radialSegments = 16,
      heightSegments = 1,
      thetaStart = 0,
      thetaLength = MathUtils.TWO_PI,
      openEnded = false,
      sideUvRepeat = [1, 1],
    } = options;

    this.radiusTop = Math.max(0, radiusTop);
    this.radiusBottom = Math.max(0, radiusBottom);
    this.height = Math.max(0, height);
    this.radialSegments = Math.max(3, Math.floor(radialSegments));
    this.heightSegments = Math.max(1, Math.floor(heightSegments));
    this.thetaStart = thetaStart;
    this.thetaLength = thetaLength;
    this.openEnded = openEnded;
    this.sideUvRepeat = [sideUvRepeat[0], sideUvRepeat[1]];

    this.generateGeometryData();
  }

  /** @inheritdoc */
  protected override generateGeometryData(): void {
    const hh = this.height / 2.0;
    const rings: LatheRing[] = [];
    for (let y = 0; y <= this.heightSegments; y++) {
      const vCoord = y / this.heightSegments;
      rings.push({
        outer: vCoord * (this.radiusTop - this.radiusBottom) + this.radiusBottom,
        y: vCoord * this.height - hh,
      });
    }

    const core = new LatheGeometry({
      rings,
      radialSegments: this.radialSegments,
      thetaStart: this.thetaStart,
      thetaLength: this.thetaLength,
      capTop: !this.openEnded,
      capBottom: !this.openEnded,
      sideCaps: true,
      flipInnerU: false,
      sideUvRepeat: this.sideUvRepeat,
    });
    this.setBuffers({
      vertices: core.vertices,
      uvs: core.uvs,
      indices: core.indices,
      wireframeIndices: core.wireframeIndices,
      normals: core.normals,
      adopt: true,
    });
  }
}
